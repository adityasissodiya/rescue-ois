"""Turn the TLC logs in spec/tla/logs/ into LaTeX macros for the paper.

Usage (from the repository root): python3 spec/tla/summarize.py [--out paper/generated]

Reads MandateSeed*.cfg (bounds) and logs/MandateSeed*.log (outcomes). Exits with status 1
if a log is missing or does not show the expected outcome, so a stale or failed run cannot
reach the paper. Every number in the output comes from those files.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXPECTED = {
    "MandateSeed": None,  # no violation
    "MandateSeed_handover": "NoHandover",
    "MandateSeed_stall": "NoSplitStall",
    "MandateSeed_broken": "EpochOrder",
}
MACRO = {
    "MandateSeed_handover": "Handover",
    "MandateSeed_stall": "Stall",
    "MandateSeed_broken": "Broken",
}


def _int(text: str) -> int:
    return int(text.replace(",", ""))


def _tex_int(n: int) -> str:
    return f"{n:,}".replace(",", "{,}")


def bounds(cfg: Path) -> dict[str, str]:
    text = cfg.read_text(encoding="utf-8")
    out = {}
    for key in ("NumByz", "MaxEpoch", "MaxTime", "H", "G", "Q"):
        m = re.search(rf"^\s*{key}\s*=\s*(\S+)\s*$", text, re.M)
        if not m:
            raise ValueError(f"{cfg.name}: no constant {key}")
        out[key] = m.group(1)
    for key in ("Honest", "Holders"):
        m = re.search(rf"^\s*{key}\s*=\s*\{{([^}}]*)\}}", text, re.M)
        if not m:
            raise ValueError(f"{cfg.name}: no constant {key}")
        out[key] = str(len([x for x in m.group(1).split(",") if x.strip()]))
    return out


def outcome(name: str) -> dict[str, str]:
    log = HERE / "logs" / f"{name}.log"
    if not log.exists():
        raise FileNotFoundError(f"{log} missing: run spec/tla/run_tlc.sh")
    text = log.read_text(encoding="utf-8")
    want = EXPECTED[name]
    res = {}
    m = re.search(r"TLC2 Version (\S+) of [^(]*\(rev: (\w+)\)", text)
    if not m:
        raise ValueError(f"{log.name}: no TLC version line")
    res["version"] = f"{m.group(1)} (rev.~{m.group(2)})"
    if want is None:
        if "Model checking completed. No error has been found." not in text:
            raise ValueError(
                f"{log.name}: the safety run did not complete without error"
            )
        m = re.search(
            r"([\d,]+) states generated, ([\d,]+) distinct states found", text
        )
        d = re.search(r"The depth of the complete state graph search is (\d+)", text)
        t = re.search(r"Finished in (\d+)min (\d+)s", text)
        w = re.search(r"with (\d+) workers", text)
        if not (m and d and t and w):
            raise ValueError(f"{log.name}: missing state counts or run time")
        res["generated"] = _tex_int(_int(m.group(1)))
        res["distinct"] = _tex_int(_int(m.group(2)))
        res["depth"] = d.group(1)
        res["minutes"] = str(int(t.group(1)) + (1 if int(t.group(2)) >= 30 else 0))
        res["workers"] = w.group(1)
    else:
        if f"Invariant {want} is violated" not in text:
            raise ValueError(f"{log.name}: {want} is not violated")
        res["trace"] = str(len(re.findall(r"^State \d+:", text, re.M)))
    return res


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=str(HERE.parent.parent / "paper" / "generated"))
    args = ap.parse_args()
    try:
        b = bounds(HERE / "MandateSeed.cfg")
        for name in EXPECTED:
            if name != "MandateSeed" and bounds(HERE / f"{name}.cfg") != b:
                raise ValueError(
                    f"{name}.cfg has bounds different from MandateSeed.cfg"
                )
        safety = outcome("MandateSeed")
        others = {name: outcome(name) for name in MACRO}
    except (OSError, ValueError) as exc:
        print(f"summarize: {exc}", file=sys.stderr)
        return 1
    macros = {
        "TlaVersion": safety["version"],
        "TlaHonest": b["Honest"],
        "TlaByz": b["NumByz"],
        "TlaHolders": b["Holders"],
        "TlaMaxEpoch": b["MaxEpoch"],
        "TlaMaxTime": b["MaxTime"],
        "TlaH": b["H"],
        "TlaG": b["G"],
        "TlaQ": b["Q"],
        "TlaDistinct": safety["distinct"],
        "TlaGenerated": safety["generated"],
        "TlaDepth": safety["depth"],
        "TlaMinutes": safety["minutes"],
        "TlaWorkers": safety["workers"],
    }
    for name, key in MACRO.items():
        macros[f"Tla{key}Trace"] = others[name]["trace"]
    lines = [
        "% Generated by spec/tla/summarize.py from spec/tla/logs/. Do not edit by hand."
    ]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "tla_macros.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"summarize: wrote {out / 'tla_macros.tex'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
